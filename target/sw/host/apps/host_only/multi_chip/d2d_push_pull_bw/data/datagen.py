"""Data of d2d_push_pull_bw: one HBM image of known words, and the header naming it.

    datagen.py --header          C header on stdout
    datagen.py --hbm-dir <dir>   <dir>/manifest.txt + the image it lists

Word i of the image is (TAG << 48) | i, so any copy of it is checked without a golden.
"""
import argparse
import pathlib
import struct

IMAGE_BYTES = 2 * 1024 * 1024
TAG = 0x5055  # "PU"


def header():
    return "\n".join(["// Generated by datagen.py -- do not edit.", "#pragma once", "",
                      f"#define BW_IMAGE_BYTES {IMAGE_BYTES}ULL",
                      f"#define BW_TAG         0x{TAG:x}ULL", ""])


def write_image(out):
    out.mkdir(parents=True, exist_ok=True)
    words = IMAGE_BYTES // 8
    (out / "image.bin").write_bytes(b"".join(struct.pack("<Q", (TAG << 48) | i)
                                             for i in range(words)))
    (out / "manifest.txt").write_text("# offset (above the HBM base)  file\n0x0  image.bin\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--header", action="store_true")
    ap.add_argument("--hbm-dir", type=pathlib.Path)
    args = ap.parse_args()
    if args.header:
        print(header(), end="")
    if args.hbm_dir:
        write_image(args.hbm_dir)
