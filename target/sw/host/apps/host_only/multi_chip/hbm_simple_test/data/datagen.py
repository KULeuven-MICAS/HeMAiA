"""Data of hbm_simple_test: the HBM image the testharness loads, and the header that
tells the test where it is.

    datagen.py --header          C header on stdout
    datagen.py --hbm-dir <dir>   <dir>/manifest.txt + the files it lists

Word i of an image file is (tag << 48) | i, so the test checks any word without
carrying a copy of the data.
"""
import argparse
import pathlib
import struct

# (name, offset above the HBM base, bytes, tag). HIGH sits above 4 GiB so its
# address needs more than 32 bits of chip-local offset.
IMAGES = [
    ("LOW", 0x0, 64 * 1024, 0x4C4F),
    ("HIGH", 0x2_4000_0000, 4 * 1024, 0x4849),
]
# Free HBM the test writes to: CPU stores, then a DMA copy.
SCRATCH_OFF = 0x3_0000_1000
COPY_BYTES = 8 * 1024


def header():
    lines = ["// Generated by datagen.py -- do not edit.", "#pragma once", ""]
    for name, off, size, tag in IMAGES:
        lines += [f"#define HBM_{name}_OFF   0x{off:x}ULL",
                  f"#define HBM_{name}_WORDS {size // 8}",
                  f"#define HBM_{name}_TAG   0x{tag:x}ULL"]
    lines += [f"#define HBM_SCRATCH_OFF 0x{SCRATCH_OFF:x}ULL",
              f"#define HBM_COPY_BYTES  {COPY_BYTES}"]
    return "\n".join(lines) + "\n"


def write_image(out):
    out.mkdir(parents=True, exist_ok=True)
    manifest = ["# offset (above the HBM base)  file"]
    for name, off, size, tag in IMAGES:
        path = out / f"{name.lower()}.bin"
        path.write_bytes(b"".join(struct.pack("<Q", (tag << 48) | i) for i in range(size // 8)))
        manifest.append(f"0x{off:x}  {path.name}")
    (out / "manifest.txt").write_text("\n".join(manifest) + "\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--header", action="store_true")
    ap.add_argument("--hbm-dir", type=pathlib.Path)
    args = ap.parse_args()
    if args.header:
        print(header(), end="")
    if args.hbm_dir:
        write_image(args.hbm_dir)
