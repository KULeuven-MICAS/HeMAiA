"""Data of memchip_multi_engine: a different SRAM image and HBM image for each of the two
memory chips of hemaia_cmc_16MBL3_1cluster, and the header naming their tags.

    datagen.py --header          C header on stdout
    datagen.py --build-dir <dir> <dir>/mempool.bin            memory chip A (1,0), the
                                 <dir>/mempool_chip_1_1.bin   shared image; B (1,1)'s own
                                 <dir>/hbm/manifest.txt       one HBM image per chip,
                                                              tagged chip=<id>

Word i of an image is (tag << 48) | i, a tag per image, so a copy of it is checked without
a golden and a word from the wrong chip's image cannot pass.
"""
import argparse
import pathlib
import struct

HBM_IMAGE_BYTES = 2 * 1024 * 1024
L4_IMAGE_BYTES = 64 * 1024
TAGS = {"L4_TAG_A": 0x4C41, "L4_TAG_B": 0x4C42,     # "LA" / "LB"
        "HBM_TAG_A": 0x4841, "HBM_TAG_B": 0x4842}   # "HA" / "HB"
MEM_A, MEM_B = 0x10, 0x11


def header():
    lines = ["// Generated by datagen.py -- do not edit.", "#pragma once", "",
             f"#define HBM_IMAGE_BYTES {HBM_IMAGE_BYTES}ULL",
             f"#define L4_IMAGE_BYTES  {L4_IMAGE_BYTES}ULL"]
    lines += [f"#define {k:<15} 0x{v:x}ULL" for k, v in TAGS.items()]
    return "\n".join(lines) + "\n"


def image(tag, nbytes):
    return b"".join(struct.pack("<Q", (tag << 48) | i) for i in range(nbytes // 8))


def write_build(out):
    (out / "hbm").mkdir(parents=True, exist_ok=True)
    (out / "mempool.bin").write_bytes(image(TAGS["L4_TAG_A"], L4_IMAGE_BYTES))
    (out / "mempool_chip_1_1.bin").write_bytes(image(TAGS["L4_TAG_B"], L4_IMAGE_BYTES))
    (out / "hbm" / "image_a.bin").write_bytes(image(TAGS["HBM_TAG_A"], HBM_IMAGE_BYTES))
    (out / "hbm" / "image_b.bin").write_bytes(image(TAGS["HBM_TAG_B"], HBM_IMAGE_BYTES))
    (out / "hbm" / "manifest.txt").write_text(
        "# offset (above the HBM base)  file  chip\n"
        f"0x0  image_a.bin  chip=0x{MEM_A:02x}\n"
        f"0x0  image_b.bin  chip=0x{MEM_B:02x}\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--header", action="store_true")
    ap.add_argument("--build-dir", type=pathlib.Path)
    args = ap.parse_args()
    if args.header:
        print(header(), end="")
    if args.build_dir:
        write_build(args.build_dir)
