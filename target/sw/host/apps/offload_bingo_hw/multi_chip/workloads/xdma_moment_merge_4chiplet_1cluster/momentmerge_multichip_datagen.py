# Data generator for the CROSS-CHIPLET in-fabric moment-merge (Gate A). Emits the
# same 4 (m,l) FP32 pairs + golden merged (m*,l*) as the P=4 cross-cluster point,
# but here the four partials live on four different COMPUTE CHIPLETS (00, 01, 10,
# 11) and the fold crosses the die-to-die link. Still ONE beat, ONE triggering
# transfer: UnifiedMonoidMergeRt (MOMENT mode) folds up to 8 lanes per beat -- the
# chiplet count only changes the live-lane count (nvalid), not the mechanism.

import os
import sys

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import moment_merge_golden, f32_bits  # noqa: E402

# Chiplet index i (REQUIRED_CHIPLETS order 00,01,10,11) owns (M_VALS[i], L_VALS[i]).
M_VALS = [1.0, 3.0, 2.0, -1.0]
L_VALS = [2.0, 0.5, 1.0, 3.0]
CHECK_TOLERANCE = 0.02  # 4-term sum, LUT-exp calls -- same bound as the P4 cross-cluster point


def _u32_array(name: str, vals) -> list:
    lines = [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(4))) = {{"]
    lines.append("    " + ", ".join(f"0x{v:08x}" for v in vals) + ",")
    lines.append("};")
    return lines


def emit_header_file(**kwargs) -> str:
    # Interleaved [m0,l0, m1,l1, m2,l2, m3,l3]: each chiplet's own (m_i,l_i) is one
    # contiguous 8-byte record, so a chiplet loads it with a SINGLE idma copy -- i.e.
    # ONE root node per chiplet, which the cross-chiplet start-broadcast requires
    # (a per-chiplet kickoff can arm only one (cluster,core) cell).
    ml_bits = []
    for m, l in zip(M_VALS, L_VALS):
        ml_bits += [f32_bits(m), f32_bits(l)]
    m_star, l_star = moment_merge_golden(M_VALS, L_VALS)
    golden_pair = [f32_bits(m_star), f32_bits(l_star)]

    lines = [
        "// Auto-generated by momentmerge_multichip_datagen.py",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    lines += _u32_array("mm_mc_ml_vals", ml_bits)
    lines.append("")
    lines += _u32_array("mm_mc_golden_pair", golden_pair)
    lines.append("")
    lines.append(f"// golden (m*,l*) = ({m_star:.6f}, {l_star:.6f})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(emit_header_file())
