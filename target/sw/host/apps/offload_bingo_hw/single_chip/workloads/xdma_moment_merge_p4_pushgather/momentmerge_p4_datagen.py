# Data generator for the F3 S3 P=4 in-fabric moment-merge scaling point. Emits
# 4 (m,l) FP32 pairs plus the golden merged (m*,l*). Still ONE beat, ONE
# triggering transfer (StreamMomentMergeRt folds up to 8 lanes per beat) --
# P=4 only changes the live-lane count (nvalid), not the mechanism.

import os
import sys

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import moment_merge_golden, f32_bits  # noqa: E402

M_VALS = [1.0, 3.0, 2.0, -1.0]
L_VALS = [2.0, 0.5, 1.0, 3.0]
CHECK_TOLERANCE = 0.02  # slightly looser than P2: 4-term sum, more LUT-exp calls


def _u32_array(name: str, vals) -> list:
    lines = [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(4))) = {{"]
    lines.append("    " + ", ".join(f"0x{v:08x}" for v in vals) + ",")
    lines.append("};")
    return lines


def emit_header_file(**kwargs) -> str:
    m_bits = [f32_bits(v) for v in M_VALS]
    l_bits = [f32_bits(v) for v in L_VALS]
    m_star, l_star = moment_merge_golden(M_VALS, L_VALS)
    golden_pair = [f32_bits(m_star), f32_bits(l_star)]

    lines = [
        "// Auto-generated by momentmerge_p4_datagen.py",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    lines += _u32_array("mm_p4_m_vals", m_bits)
    lines.append("")
    lines += _u32_array("mm_p4_l_vals", l_bits)
    lines.append("")
    lines += _u32_array("mm_p4_golden_pair", golden_pair)
    lines.append("")
    lines.append(f"// golden (m*,l*) = ({m_star:.6f}, {l_star:.6f})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(emit_header_file())
