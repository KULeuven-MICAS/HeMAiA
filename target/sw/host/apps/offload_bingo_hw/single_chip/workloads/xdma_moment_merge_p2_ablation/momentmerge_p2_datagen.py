# Data generator for the F3 S2 gather-then-local ablation baseline. Uses the
# EXACT SAME (m,l) values and golden as the sibling xdma_moment_merge_p2_infabric
# workload, so the two workloads' measured latency/bytes are directly comparable
# -- only the locus of the fold differs (in-fabric push vs. raw cross-cluster
# copy + a separate local pass), matching tmp/f3-cross-cluster-collective-cfg.md
# S6.1's "identical local-partial computation, identical loci P" control.

import os
import sys

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import moment_merge_golden, f32_bits  # noqa: E402

M_VALS = [1.0, 3.0]
L_VALS = [2.0, 0.5]
CHECK_TOLERANCE = 0.015


def _u32_array(name: str, vals) -> list:
    lines = [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(4))) = {{"]
    lines.append("    " + ", ".join(f"0x{v:08x}" for v in vals) + ",")
    lines.append("};")
    return lines


def emit_header_file(**kwargs) -> str:
    m_bits = [f32_bits(v) for v in M_VALS]
    l_bits = [f32_bits(v) for v in L_VALS]
    m_star, l_star = moment_merge_golden(M_VALS, L_VALS)
    golden_pair = [f32_bits(m_star), f32_bits(l_star)]

    lines = [
        "// Auto-generated by momentmerge_p2_datagen.py (S2 ablation)",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    lines += _u32_array("mm_p2_m_vals", m_bits)
    lines.append("")
    lines += _u32_array("mm_p2_l_vals", l_bits)
    lines.append("")
    lines += _u32_array("mm_p2_golden_pair", golden_pair)
    lines.append("")
    lines.append(f"// golden (m*,l*) = ({m_star:.6f}, {l_star:.6f})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(emit_header_file())
