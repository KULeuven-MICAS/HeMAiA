# Data generator for the F3 S1 P=2 in-fabric moment-merge collective (the flag's
# first cross-cluster measured point). Emits 2 (m,l) FP32 pairs as compile-time
# constants (mm_p2_m_vals[2], mm_p2_l_vals[2]) plus the golden merged (m*,l*),
# splatted across a 64B beat matching StreamMomentMergeRt's output layout
# (Cat(Seq.fill(8)(Cat(lStar,mStar))) -> 8x[m*,l*] uint32 pairs).
#
# Both producers' values are baked as shared compile-time constants (not
# computed on-cluster) -- this bring-up tests the CROSS-CLUSTER IN-FABRIC FOLD
# mechanism (writerExtCfg carrying the armed extension across the link), not
# per-cluster local softmax-statistic computation, which is a later
# integration step (see tmp/f3-cross-cluster-collective-cfg.md S6.5).

import os
import sys

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import moment_merge_golden, f32_bits  # noqa: E402

M_VALS = [1.0, 3.0]
L_VALS = [2.0, 0.5]
# golden (m*,l*) = (3.0, 0.770671) -- l* rel-err tolerance is 1.5e-2 (~0.0116);
# CHECK_TOLERANCE below is an absolute bound sized for this magnitude.
CHECK_TOLERANCE = 0.015


def _u32_array(name: str, vals) -> list:
    lines = [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(4))) = {{"]
    lines.append("    " + ", ".join(f"0x{v:08x}" for v in vals) + ",")
    lines.append("};")
    return lines


def emit_header_file(**kwargs) -> str:
    m_bits = [f32_bits(v) for v in M_VALS]
    l_bits = [f32_bits(v) for v in L_VALS]
    m_star, l_star = moment_merge_golden(M_VALS, L_VALS)
    m_star_bits = f32_bits(m_star)
    l_star_bits = f32_bits(l_star)
    golden_pair = [m_star_bits, l_star_bits]  # low 64b of the landed beat: m* then l*

    lines = [
        "// Auto-generated by momentmerge_p2_datagen.py",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    lines += _u32_array("mm_p2_m_vals", m_bits)
    lines.append("")
    lines += _u32_array("mm_p2_l_vals", l_bits)
    lines.append("")
    lines += _u32_array("mm_p2_golden_pair", golden_pair)
    lines.append("")
    lines.append(f"// golden (m*,l*) = ({m_star:.6f}, {l_star:.6f})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(emit_header_file())
