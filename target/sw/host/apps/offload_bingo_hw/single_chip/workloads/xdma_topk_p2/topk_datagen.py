# Datagen for the top-k routing monoid (3rd monoid of the collective algebra): distributed MoE
# expert selection. E experts are sharded across NUM_SHARDS clusters (EXPERTS_PER_SHARD each); each
# cluster scores its own experts and pushes its local (logit, expert-id) candidate list. The in-fabric
# StreamTopKMergeRt sorts+merges the shards' lists into the running GLOBAL top-8 routing table; the host
# reads the top-k prefix. Golden = the direct global top-8 sorted descending by (logit, then SMALLER id).
#
# Because the sort network only ROUTES (value,index) pairs through muxes -- no arithmetic -- the output
# beat is a BIT-EXACT selection of the input pairs, so the check is BYTE_EXACT over the whole 64 B table
# (verifies both the top-k logits AND their expert indices). DISTINCT logits (distinct-value invariant)
# make the ordering unambiguous, so the host/golden tie-break convention is never exercised.
#
# Beat layout matches the extension: value_k = lane k (bytes 4k..4k+3), index_k = lane (8+k)
# (bytes 32+4k..). One 64 B beat = up to 8 candidate (logit, expert-id) pairs; nvalid = EXPERTS_PER_SHARD.

import os
import sys
import numpy as np

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import f32_bits  # noqa: E402

NUM_SHARDS       = 2
EXPERTS_PER_SHARD = 8            # 8 experts/cluster -> 16 experts total; one 64 B beat holds 8 candidates
M                = 8            # slot capacity = candidates per beat (top-M kept; SW reads top-k <= M)
SEED             = 0x70B1


def _build():
    """Return (shard_beats[NUM_SHARDS][2M u32], golden_beat[2M u32]).
    shard i owns experts [i*EPS .. i*EPS+EPS-1] with DISTINCT logits; golden = global top-M."""
    rng = np.random.default_rng(SEED)
    eps = EXPERTS_PER_SHARD
    total = NUM_SHARDS * eps
    # distinct logits: normal draws, then nudge any fp32 collision (astronomically unlikely, but be exact)
    logits = rng.normal(0.0, 2.0, size=total).astype(np.float32)
    seen = set()
    for i in range(total):
        while int(logits[i].view(np.uint32)) in seen:
            logits[i] = np.float32(float(logits[i]) + 1e-3)
        seen.add(int(logits[i].view(np.uint32)))
    experts = [(float(logits[j]), j) for j in range(total)]  # (logit, global expert-id)

    def pack(pairs):
        beat = np.zeros(2 * M, dtype=np.uint32)
        for k, (v, idx) in enumerate(pairs[:M]):
            beat[k]     = f32_bits(v)
            beat[M + k] = np.uint32(idx)
        # lanes beyond len(pairs) stay 0; the RTL masks lanes >= nValid to the identity, so 0 is don't-care
        return beat

    shard_beats = []
    for s in range(NUM_SHARDS):
        local = experts[s * eps:(s + 1) * eps]           # this shard's EPS experts (already its local top-M)
        shard_beats.append(pack(local))

    # global top-M: sort ALL experts descending by logit, ties -> smaller expert-id (matches the RTL cex)
    gtopk = sorted(experts, key=lambda p: (-p[0], p[1]))[:M]
    golden_beat = pack(gtopk)
    return shard_beats, golden_beat, gtopk


def _u32(name, vals):
    return [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(64))) = {{",
            "    " + ", ".join(f"0x{int(v) & 0xffffffff:08x}" for v in vals) + ",", "};"]


def emit_header_file(**kwargs):
    shard_beats, golden_beat, gtopk = _build()
    flat = np.concatenate(shard_beats).astype(np.uint32)  # NUM_SHARDS * 2M u32
    lines = ["// Auto-generated by topk_datagen.py -- distributed MoE top-k routing monoid.",
             "#pragma once", "#include <stdint.h>", "",
             f"#define TOPK_NUM_SHARDS {NUM_SHARDS}",
             f"#define TOPK_EXPERTS_PER_SHARD {EXPERTS_PER_SHARD}",
             f"#define TOPK_M {M}", ""]
    lines += _u32("topk_shard_beats", flat.tolist()); lines.append("")     # 2 beats, 64 B each
    lines += _u32("topk_golden_beat", golden_beat.tolist()); lines.append("")  # 64 B sorted top-8 table
    top2 = gtopk[:2]
    lines.append(f"// global top-2 routing: expert {top2[0][1]} (logit {top2[0][0]:.4f}), "
                 f"expert {top2[1][1]} (logit {top2[1][0]:.4f})")
    return "\n".join(lines) + "\n"


