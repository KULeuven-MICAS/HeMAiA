# Datagen for the COMPLETE distributed flash-attention collective -- the (m, ell, O) triple
# (StreamAttnMergeRt, `10-new-capabilities.md` / `07 §2b`). Each of NUM_SHARDS clusters owns a KV block and
# computes its local flash-attention partial (m_k, ell_k, O_k), O_k[j] = Σ_i exp(s_i - m_k)·v_i[j]. The
# in-fabric fold combines them into the GLOBAL (m*, ell*, O*):
#   m* = max_k m_k;  ell* = Σ_k ell_k·exp(m_k - m*);  O*[j] = Σ_k O_k[j]·exp(m_k - m*)
# so the whole distributed attention (not just the softmax normalizer) is computed in the mover; the host
# does one final O*/ell* divide. Golden = the direct global partial over all shards' (scores, values), which
# the fold must reproduce within LUT-exp tolerance.
#
# Beat layout: m at lane 0, ell at lane 1, O[0..dHead-1] at lanes 2..(2+dHead-1) (one shard's partial/beat).

import os
import sys
import numpy as np

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import f32_bits  # noqa: E402

NUM_SHARDS = 2
D_HEAD     = 8              # must match the RTL HasStreamAttnMergeRt dHead; 2+dHead <= 16 lanes
L_KV       = 16            # keys per shard (KV block length)
SEED       = 0x0A11
CHECK_TOLERANCE = 1.0      # absolute tol; ell ~ O(L), O ~ O(L*|v|); LUT-exp rel err ~1.5e-2


def _shard_partial(scores, values):
    m = float(np.max(scores))
    w = np.exp(scores - m)
    ell = float(np.sum(w))
    O = (w[:, None] * values).sum(axis=0)  # [D_HEAD]
    return m, ell, O.astype(np.float64)


def _build():
    rng = np.random.default_rng(SEED)
    shard_scores, shard_values, partials = [], [], []
    for _ in range(NUM_SHARDS):
        s = rng.normal(0.0, 2.0, size=L_KV)
        v = rng.normal(0.0, 1.5, size=(L_KV, D_HEAD))
        shard_scores.append(s); shard_values.append(v)
        partials.append(_shard_partial(s, v))
    # golden = the DIRECT global partial over all shards' (scores, values)
    all_s = np.concatenate(shard_scores)
    all_v = np.concatenate(shard_values, axis=0)
    gm, gell, gO = _shard_partial(all_s, all_v)
    return partials, (gm, gell, gO)


def _pack(m, ell, O):
    beat = np.zeros(16, dtype=np.uint32)   # 512-bit beat, 16 fp32 lanes
    beat[0] = f32_bits(m)
    beat[1] = f32_bits(ell)
    for k in range(D_HEAD):
        beat[2 + k] = f32_bits(float(O[k]))
    return beat


def emit_header_file(**kwargs):
    partials, (gm, gell, gO) = _build()
    shard_beats = [_pack(m, ell, O) for (m, ell, O) in partials]
    flat = np.concatenate(shard_beats).astype(np.uint32)
    # golden = (m*, ell*, O*[dHead]) = 2 + dHead fp32, in beat order
    golden = [f32_bits(gm), f32_bits(gell)] + [f32_bits(float(gO[k])) for k in range(D_HEAD)]

    lines = ["// Auto-generated by attn_datagen.py -- the complete distributed flash-attention (m,ell,O) triple.",
             "#pragma once", "#include <stdint.h>", "",
             f"#define ATTN_NUM_SHARDS {NUM_SHARDS}",
             f"#define ATTN_D_HEAD {D_HEAD}",
             f"#define ATTN_GOLDEN_ELEMS {2 + D_HEAD}", ""]
    lines += [f"static uint32_t attn_shard_beats[{len(flat)}] __attribute__((aligned(64))) = {{",
              "    " + ", ".join(f"0x{int(v)&0xffffffff:08x}" for v in flat.tolist()) + ",", "};", ""]
    lines += [f"static uint32_t attn_golden[{len(golden)}] __attribute__((aligned(64))) = {{",
              "    " + ", ".join(f"0x{int(v)&0xffffffff:08x}" for v in golden) + ",", "};", ""]
    onorm = gO / gell
    lines.append(f"// global (m*, ell*) = ({gm:.4f}, {gell:.4f}); attention out O*/ell* = "
                 f"[{', '.join(f'{x:.3f}' for x in onorm[:4])}, ...]")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    partials, (gm, gell, gO) = _build()
    # self-check: folding the per-shard partials reproduces the direct global partial
    mstar = max(p[0] for p in partials)
    ellf = sum(p[1] * np.exp(p[0] - mstar) for p in partials)
    Of = sum(p[2] * np.exp(p[0] - mstar) for p in partials)
    assert abs(ellf - gell) < 1e-9 and np.allclose(Of, gO, atol=1e-9), "fold != direct global!"
    print(f"[attn] {NUM_SHARDS} shards, dHead={D_HEAD}, L_KV={L_KV}; global (m*,ell*)=({gm:.4f},{gell:.4f}); "
          f"fold==direct global (self-check OK). O*/ell* head0={gO[0]/gell:.4f}")
