# Datagen for the norm-stat monoid (2nd monoid of the collective algebra): distributed
# LayerNorm/RMSNorm statistics. Two shards each provide their local (Sx, Sxx) = (Σx, Σx²);
# the in-fabric fold sums them into the global (Σx, Σx²). Golden = the direct global sums.
# The host would then project mean = Σx/n, var = Σx²/n − mean²; here we check the folded
# (Σx, Σx²) pair directly (that is what the extension produces).

import os
import sys
import numpy as np

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import f32_bits  # noqa: E402

NUM_SHARDS = 2
S_P = 256                      # elements per shard (equal shards)
SEED = 0x503A
CHECK_TOLERANCE = 2.0          # ABSOLUTE tol; Σx² ~ O(S_P) so scale the tol accordingly


def _build():
    rng = np.random.default_rng(SEED)
    shards = [rng.normal(0.0, 1.0, size=S_P).astype(np.float32) for _ in range(NUM_SHARDS)]
    sx = [float(np.sum(s)) for s in shards]
    sxx = [float(np.sum(s * s)) for s in shards]
    sx_star = float(np.sum(sx))
    sxx_star = float(np.sum(sxx))
    return sx, sxx, sx_star, sxx_star


def _u32(name, vals):
    return [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(4))) = {{",
            "    " + ", ".join(f"0x{v:08x}" for v in vals) + ",", "};"]


def emit_header_file(**kwargs):
    sx, sxx, sx_star, sxx_star = _build()
    lines = ["// Auto-generated by normstat_datagen.py -- distributed norm-stat monoid.",
             "#pragma once", "#include <stdint.h>", "",
             f"#define NORMSTAT_NUM_SHARDS {NUM_SHARDS}", ""]
    lines += _u32("normstat_sx_vals", [f32_bits(v) for v in sx]); lines.append("")
    lines += _u32("normstat_sxx_vals", [f32_bits(v) for v in sxx]); lines.append("")
    lines += _u32("normstat_golden_pair", [f32_bits(sx_star), f32_bits(sxx_star)]); lines.append("")
    lines.append(f"// golden (Σx, Σx²) = ({sx_star:.6f}, {sxx_star:.6f})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sx, sxx, a, b = _build()
    print(f"[normstat] shards Σx={[round(v,3) for v in sx]} Σx²={[round(v,3) for v in sxx]}; golden ({a:.4f},{b:.4f})")
