# Gate 1 datagen: isolate the two UNTESTED mechanisms E-d depends on, before any
# cross-cluster wiring:
#   (a) an out_fp32 StreamReduce/MapReduce whose scalar lands as FP32 in the beat;
#   (b) the runtime a_addr path -- a StreamMapReduce that reads its multiply operand
#       `a` from an L1 FP32 word a producer wrote, instead of a compile-time immediate.
#
# The graph is: scores --SumExp(out_fp32)--> sum_f32
#               ones_beat --LINEAR(a=a_addr=sum_f32, MAX, out_fp32)--> l_f32
# and we check l_f32 == sum_exp (since the "ones" input is 1.0 in every lane and
# MAX over identical lanes returns the value, l = a*1 = sum). If a_addr is wired
# right, the device reproduces the host-computed sum_exp.

import os
import sys
import numpy as np

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import f32_bits  # noqa: E402

N = 128            # scores (must be a whole number of 32-lane FP16 beats)
SCORE_MAX = 6.0
SEED = 0xED01
CHECK_TOLERANCE = 3.0  # ABSOLUTE tol; sum_exp ~ 900, datapath LUT-exp gives ~0.02% (~0.2 abs)


def _build(**_):
    assert N % 32 == 0
    rng = np.random.default_rng(SEED)
    scores = np.minimum(rng.normal(1.0, 1.5, size=N).astype(np.float32), SCORE_MAX)
    scores = np.float16(scores)
    sum_exp = float(np.sum(np.exp(scores.astype(np.float64))))
    return scores, sum_exp


def _u16(name, arr):
    u16 = arr.view(np.uint16)
    return [f"static uint16_t {name}[{len(u16)}] __attribute__((aligned(64))) = {{",
            "    " + ", ".join(f"0x{v:04x}" for v in u16.tolist()) + ",", "};"]


def _u16_const(name, value, n):
    u16 = np.full(n, np.float16(value)).view(np.uint16)
    return [f"static uint16_t {name}[{len(u16)}] __attribute__((aligned(64))) = {{",
            "    " + ", ".join(f"0x{v:04x}" for v in u16.tolist()) + ",", "};"]


def _u32(name, vals):
    return [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(4))) = {{",
            "    " + ", ".join(f"0x{v:08x}" for v in vals) + ",", "};"]


def emit_header_file(**kwargs):
    scores, sum_exp = _build(**kwargs)
    lines = ["// Auto-generated by ed_gate1_datagen.py", "#pragma once", "#include <stdint.h>", "",
             f"#define G1_N {N}", f"#define G1_BEATS {N // 32}", ""]
    lines += _u16("g1_scores", scores); lines.append("")
    lines += _u16_const("g1_ones", 1.0, 32); lines.append("")   # one beat of 1.0
    lines += _u32("g1_golden", [f32_bits(sum_exp)]); lines.append("")
    lines.append(f"// golden sum_exp = {sum_exp:.6f}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    scores, sum_exp = _build()
    print(f"[Gate 1] N={N}, sum_exp={sum_exp:.6f}, max(exp)={np.exp(scores.astype(np.float64)).max():.1f}")
