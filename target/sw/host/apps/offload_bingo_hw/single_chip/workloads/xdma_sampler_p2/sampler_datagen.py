# Datagen for the IN-FABRIC SAMPLER (tier-jump, `10-new-capabilities.md`): distributed token sampling is an
# EXACT monoid fold on the SAME top-k substrate the collective already measures (StreamTopKMergeRt) -- NO new
# RTL. Gumbel-max: i* = argmax_i (logit_i + g_i), g_i ~ Gumbel(0,1) iid  ==exact==> i* ~ softmax(logit).
# Each shard perturbs ITS OWN logits with local Gumbel noise; the cross-shard argmax fold (the top-1 of the
# top-k monoid) yields the sampled token. The full distribution is never gathered.
#
# This datagen bakes ONE Gumbel draw (deterministic), chosen so the SAMPLED token differs from the GREEDY
# token -- to make the point that this is stochastic sampling, not argmax of the raw logits. The check is
# byte-exact on the whole sorted top-8 table (values AND token ids), so the top-1 = the sampled token is
# verified in-fabric. (The distribution-level exactness is proven in numpy, scratchpad/sampler_poc.py.)
#
# Beat layout (identical to the top-k monoid): perturbed_value_k = lane k (fp32), token_id_k = lane (8+k).

import os
import sys
import numpy as np

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import f32_bits  # noqa: E402

NUM_SHARDS      = 2
VOCAB_PER_SHARD = 8            # 8 tokens/shard -> 16-token vocab; one 64 B beat holds 8 candidates
M               = 8            # top-M kept; the top-1 is the sampled token
SEED            = 0x5A3B


def _softmax(x):
    x = x - x.max()
    e = np.exp(x)
    return e / e.sum()


def _gumbel(rng, n):
    u = rng.uniform(1e-12, 1.0, size=n)
    return -np.log(-np.log(u))


def _build():
    """16-token vocab sharded 8+8; local Gumbel perturbation; sampled token = global argmax(logit+g).
    Retry the noise draw until the sampled token != the greedy token (to demonstrate stochasticity)."""
    eps = VOCAB_PER_SHARD
    total = NUM_SHARDS * eps
    seed = SEED
    for attempt in range(64):
        rng = np.random.default_rng(seed + attempt)
        logit = rng.normal(0.0, 2.0, size=total).astype(np.float32)
        # distinct logits (fp32) so ordering is unambiguous
        seen = set()
        for i in range(total):
            while int(logit[i].view(np.uint32)) in seen:
                logit[i] = np.float32(float(logit[i]) + 1e-3)
            seen.add(int(logit[i].view(np.uint32)))
        g = _gumbel(rng, total).astype(np.float32)
        perturbed = (logit + g).astype(np.float32)
        # ensure perturbed values are fp32-distinct too
        seen = set()
        ok = True
        for i in range(total):
            b = int(perturbed[i].view(np.uint32))
            if b in seen:
                ok = False
                break
            seen.add(b)
        if not ok:
            continue
        greedy = int(np.argmax(logit))
        sampled = int(np.argmax(perturbed))
        if sampled != greedy:
            return logit, g, perturbed, greedy, sampled
    raise RuntimeError("could not find a noise draw with sampled != greedy")


def _pack(pairs):
    beat = np.zeros(2 * M, dtype=np.uint32)
    for k, (v, idx) in enumerate(pairs[:M]):
        beat[k]     = f32_bits(v)
        beat[M + k] = np.uint32(idx)
    return beat


def emit_header_file(**kwargs):
    logit, g, perturbed, greedy, sampled = _build()
    total = NUM_SHARDS * VOCAB_PER_SHARD
    cand = [(float(perturbed[j]), j) for j in range(total)]  # (perturbed logit, token id)
    shard_beats = [_pack(cand[s * VOCAB_PER_SHARD:(s + 1) * VOCAB_PER_SHARD]) for s in range(NUM_SHARDS)]
    gtop = sorted(cand, key=lambda p: (-p[0], p[1]))[:M]     # global sorted top-M of perturbed; top-1 = sample
    golden = _pack(gtop)
    flat = np.concatenate(shard_beats).astype(np.uint32)

    p = _softmax(logit.astype(np.float64))
    lines = ["// Auto-generated by sampler_datagen.py -- the in-fabric SAMPLER (distributed token sampling",
             "// = a monoid fold on the top-k substrate; Gumbel-max). The top-1 of the folded table is the",
             "// sampled token. This reuses StreamTopKMergeRt UNCHANGED -- no new RTL.",
             "#pragma once", "#include <stdint.h>", "",
             f"#define SAMPLER_NUM_SHARDS {NUM_SHARDS}",
             f"#define SAMPLER_VOCAB_PER_SHARD {VOCAB_PER_SHARD}",
             f"#define SAMPLER_M {M}", ""]
    lines += [f"static uint32_t sampler_shard_beats[{len(flat)}] __attribute__((aligned(64))) = {{",
              "    " + ", ".join(f"0x{int(v)&0xffffffff:08x}" for v in flat.tolist()) + ",", "};", ""]
    lines += [f"static uint32_t sampler_golden_beat[{len(golden)}] __attribute__((aligned(64))) = {{",
              "    " + ", ".join(f"0x{int(v)&0xffffffff:08x}" for v in golden.tolist()) + ",", "};", ""]
    lines.append(f"// greedy token = {greedy} (softmax prob {p[greedy]:.3f});  SAMPLED token = {sampled} "
                 f"(softmax prob {p[sampled]:.3f})  [sampled != greedy => stochastic]")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    logit, g, perturbed, greedy, sampled = _build()
    p = _softmax(logit.astype(np.float64))
    print(f"[sampler] 16-token vocab, 2 shards; greedy={greedy} (p={p[greedy]:.3f}), "
          f"SAMPLED={sampled} (p={p[sampled]:.3f}); sampled!=greedy => stochastic. "
          f"Gumbel-max folds via the top-k monoid.")
