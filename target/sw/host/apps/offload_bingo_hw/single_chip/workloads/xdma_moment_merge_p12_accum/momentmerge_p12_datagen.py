# Datagen for the P=12 accumulate demonstration: 12 (m,l) partials merged by the collective
# with accumulate-on-arrival (accEn), on a 2-CLUSTER platform. This is the experiment that
# proves the "no P<=8 lane wall" claim: the stateless fold caps at maxPairs=8 lanes per beat,
# but accEn folds each arriving beat INTO a persistent slot, so P is bounded only by how many
# pushes happen -- here 2 clusters x 6 pushes = 12 shards > 8, which the stateless path
# cannot express in one collective.

import os
import sys

current_dir = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.normpath(os.path.join(current_dir, "../../../../../../../../"))
sys.path.append(os.path.join(ROOT_DIR, "util", "sim"))
from xdma_moment_merge_golden import moment_merge_golden, f32_bits  # noqa: E402

NUM_SHARDS = 12
# distinct, spread (m,l) so the fold's exp(delta) is meaningfully != 1 across all 12 partials
M_VALS = [1.0, 3.0, 2.0, -1.0, 0.5, 4.0, -2.0, 2.5, 1.5, 3.5, -0.5, 0.0]
L_VALS = [2.0, 0.5, 1.0, 3.0, 1.5, 0.25, 4.0, 0.75, 2.5, 0.4, 3.5, 1.25]
CHECK_TOLERANCE = 0.05  # 12-term sum, more LUT-exp calls than P=4 -> a touch looser


def _u32_array(name, vals):
    lines = [f"static uint32_t {name}[{len(vals)}] __attribute__((aligned(4))) = {{"]
    lines.append("    " + ", ".join(f"0x{v:08x}" for v in vals) + ",")
    lines.append("};")
    return lines


def emit_header_file(**kwargs):
    assert len(M_VALS) == NUM_SHARDS and len(L_VALS) == NUM_SHARDS
    m_star, l_star = moment_merge_golden(M_VALS, L_VALS)
    lines = ["// Auto-generated by momentmerge_p12_datagen.py -- 12-shard accumulate demo.",
             "#pragma once", "#include <stdint.h>", "",
             f"#define MM_P12_NUM_SHARDS {NUM_SHARDS}", ""]
    lines += _u32_array("mm_p12_m_vals", [f32_bits(v) for v in M_VALS]); lines.append("")
    lines += _u32_array("mm_p12_l_vals", [f32_bits(v) for v in L_VALS]); lines.append("")
    lines += _u32_array("mm_p12_golden_pair", [f32_bits(m_star), f32_bits(l_star)]); lines.append("")
    lines.append(f"// golden (m*,l*) over 12 shards = ({m_star:.6f}, {l_star:.6f})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ms, ls = moment_merge_golden(M_VALS, L_VALS)
    print(f"[P=12] golden (m*,l*)=({ms:.6f}, {ls:.6f}); {NUM_SHARDS} shards on 2 clusters")
