"""Inputs and goldens for the E2 reduce app (snax-coll-reduce).

coll_in[i] is the partial of the chip at snake position i (the app builds the snake from the
platform), nbytes of FP16 small integers in [-16, 16], so every sum over at most 16 chips is
exact in FP16 whatever the order of the fold.

The check compares SAMPLES, not the whole buffer: one 32-bit word every `stride` bytes, with
stride = 64 * ceil(span / 128 KiB) + 4, so the word inside the 64 B beat rotates from sample
to sample and every word position is hit. The root's sum is compared against coll_gold_sum,
the sampled sum over the first P partials for every P of the sweep.
"""

import argparse
import pathlib

import hjson
import numpy as np

SAMPLE_SPAN = 128 * 1024


def sample_stride(span):
    return 64 * ((span + SAMPLE_SPAN - 1) // SAMPLE_SPAN) + 4


def n_samples(span):
    return (span - 4) // sample_stride(span) + 1


def words(arr16):
    return arr16.view(np.uint32)


def emit(p):
    nbytes = int(p["nbytes"])
    chips = int(p["num_chiplets"])
    ps = [int(x) for x in p["P"]]
    assert nbytes % 4096 == 0, "nbytes must be a multiple of 4 KiB (SIMD rows, chunks)"
    assert max(ps) <= chips
    rng = np.random.default_rng(int(p.get("seed", 1)))
    data = rng.integers(-16, 17, size=(chips, nbytes // 2)).astype(np.float16)

    stride = sample_stride(nbytes)
    ns = n_samples(nbytes)
    gold = np.zeros((len(ps), ns), dtype=np.uint32)
    for i, P in enumerate(ps):
        s = data[:P].astype(np.float64).sum(axis=0).astype(np.float16)
        w = words(s)
        gold[i] = w[(np.arange(ns) * stride) // 4]

    out = []
    out.append("// Generated by datagen.py. Do not edit.")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append(f"#define COLL_NBYTES {nbytes}u")
    out.append(f"#define COLL_NCHIPS {chips}u")
    out.append(f"#define COLL_NP {len(ps)}u")
    out.append(f"#define COLL_SAMPLE_SPAN {SAMPLE_SPAN}u")
    out.append(f"#define COLL_REPEATS {int(p.get('repeats', 2))}u")
    out.append(f"#define COLL_EMPTY_REPEATS {int(p.get('empty_repeats', 2))}u")
    out.append(f"#define COLL_CHAIN_CHUNKS {int(p.get('chain_chunks', 4))}u")
    out.append(f"#define COLL_GROUP {int(p.get('group', 4))}u")
    out.append(f"#define COLL_SUM_SAMPLES {ns}u")
    # optional: run only these implementations (by name), e.g. to complete a run that stopped;
    # the ids are the app's I_* (the bits of the filter)
    ids = {"xdma": 2, "pull": 3, "chain": 5, "tree": 6, "xtree": 10, "x2l": 12}
    only = p.get("impls")
    mask = sum(1 << ids[x] for x in only) if only else 0xFFFFFFFF
    out.append(f"#define COLL_IMPL_FILTER 0x{mask:08x}u")
    out.append("static const uint32_t coll_ps[COLL_NP] = {" + ", ".join(map(str, ps)) + "};")
    out.append("// coll_in[snake position][FP16 element], as 32-bit words")
    out.append(f"uint32_t coll_in[COLL_NCHIPS][COLL_NBYTES / 4] "
               f"__attribute__((aligned(4096))) = {{")
    for c in range(chips):
        w = words(data[c])
        rows = []
        for j in range(0, w.size, 16):
            rows.append(", ".join(f"0x{x:08x}" for x in w[j:j + 16]))
        out.append("  {" + ",\n   ".join(rows) + "},")
    out.append("};")
    out.append("// coll_gold_sum[P index][sample]: the sum over the first P partials, sampled")
    out.append("uint32_t coll_gold_sum[COLL_NP][COLL_SUM_SAMPLES] __attribute__((aligned(64))) = {")
    for i in range(len(ps)):
        out.append("  {" + ", ".join(f"0x{x:08x}" for x in gold[i]) + "},")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-c", "--cfg", type=pathlib.Path, required=True)
    a = ap.parse_args()
    p = hjson.loads(a.cfg.read_text())
    print(emit(p), end="")


if __name__ == "__main__":
    main()
