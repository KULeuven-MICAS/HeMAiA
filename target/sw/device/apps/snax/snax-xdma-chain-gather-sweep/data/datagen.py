# Data generator for the cross-die ChainGather SCALING SWEEP on the 16-chiplet platform.
#
# One binary measures the in-fabric fold at several chain widths P. The chiplet sitting at
# snake index i owns partial i (see the snake order in the app source), so the participants
# of a width-P round are exactly the first P partials and the golden for that round is the
# fold over rows [0 .. P-1]. That prefix property is why a single data set serves every P.
#
# Two folds are emitted per P, matching the two junctions the app exercises:
#
#   LINEAR    ElementwiseJunction, per-element FP32 ADD.
#             golden_lin[P] = sum(data[0:P], axis=0)
#             Values are small integers so the fp32 sum is EXACT and the on-device check
#             can be a byte-exact bit-pattern compare.
#
#   MOMENT    MonoidJunction, the nonlinear online-softmax normalizer merge
#             (m1,l1) (+) (m2,l2) = (max(m1,m2), l1*exp(m1-m*) + l2*exp(m2-m*))
#             golden_mom[P] = fold over the first P (m, l) pairs.
#             MonoidJunction PAIRED layout (MOMENT, pairSlots = dataWidth/(2*accWidth)
#             = 512/64 = 8): field0 (m) at lane k, field1 (l) at lane pairSlots+k. With
#             nValid=1 only slot 0 is live, so m sits at lane 0 and l at lane 8, and the
#             folded result lands m* at lane 0, l* at lane 8. m* is exact (a max); l* goes
#             through the writer's exp LUT and is checked to a ULP tolerance on device.

import argparse
import pathlib
import hjson
import numpy as np

np.random.seed(320)

# Moment operands. The first four are the Gate-A moment-merge values, kept unchanged so the
# P=2 and P=4 results stay directly comparable with the earlier 4-chiplet measurements
# (P=4 there gave m* = 3.0, l* ~= 1.193497). The remaining twelve extend the same spread.
M_VALS = [1.0, 3.0, 2.0, -1.0, 0.5, -2.0, 2.5, 1.5,
          -0.5, 3.5, 0.0, -1.5, 2.25, 1.75, -2.5, 0.75]
L_VALS = [2.0, 0.5, 1.0, 3.0, 1.5, 2.5, 0.25, 1.25,
          3.5, 0.75, 2.75, 1.75, 0.5, 2.25, 1.0, 3.25]

PAIRSLOTS = 8   # dataWidth / (2 * accWidth) = 512 / 64


def _f(v):
    # repr(float) always carries a decimal point or exponent, so "3.0f" and never the
    # invalid "3f", and enough digits to round-trip the exact fp32 value.
    return repr(float(v)) + "f"


def emit_header_file(**kwargs):
    num_chiplets = kwargs["num_chiplets"]
    partial_elems = kwargs["partial_elems"]
    sweep_p = list(kwargs["sweep_p"])

    assert num_chiplets <= len(M_VALS), \
        f"only {len(M_VALS)} moment operands defined, need {num_chiplets}"
    assert partial_elems > PAIRSLOTS, \
        f"partial_elems ({partial_elems}) must exceed pairSlots ({PAIRSLOTS})"
    for p in sweep_p:
        assert 2 <= p <= num_chiplets, f"sweep width {p} outside [2, {num_chiplets}]"

    # ---- LINEAR: small integer-valued fp32 partials -> exact fp32 sums.
    data = np.random.randint(0, 64, size=(num_chiplets, partial_elems)).astype(np.float32)
    golden_lin = np.zeros((len(sweep_p), partial_elems), dtype=np.float32)
    for i, p in enumerate(sweep_p):
        golden_lin[i] = np.sum(data[:p], axis=0).astype(np.float32)

    # ---- MOMENT: one (m, l) pair per chiplet, m at lane 0 and l at lane PAIRSLOTS.
    # Every other lane is zero and is masked to the identity by nValid = 1.
    mom = np.zeros((num_chiplets, partial_elems), dtype=np.float32)
    for i in range(num_chiplets):
        mom[i, 0] = np.float32(M_VALS[i])
        mom[i, PAIRSLOTS] = np.float32(L_VALS[i])

    golden_mom = np.zeros((len(sweep_p), partial_elems), dtype=np.float32)
    for i, p in enumerate(sweep_p):
        m = np.array(M_VALS[:p], dtype=np.float64)
        l = np.array(L_VALS[:p], dtype=np.float64)
        m_star = float(np.max(m))
        l_star = float(np.sum(l * np.exp(m - m_star)))
        golden_mom[i, 0] = np.float32(m_star)
        golden_mom[i, PAIRSLOTS] = np.float32(l_star)

    def fvec(name, arr):
        vals = ", ".join(_f(v) for v in arr.reshape(-1))
        return f"float {name}[{arr.size}] = {{{vals}}};"

    def ivec(name, vals):
        body = ", ".join(str(int(v)) for v in vals)
        return f"static const int {name}[{len(vals)}] = {{{body}}};"

    lines = [
        "// Generated by datagen.py -- do not edit.",
        "#include <stdint.h>",
        f"#define NUM_CHIPLETS {num_chiplets}",
        f"#define PARTIAL_ELEMS {partial_elems}",
        f"#define NUM_SWEEP_P {len(sweep_p)}",
        f"#define MOMENT_M_LANE 0",
        f"#define MOMENT_L_LANE {PAIRSLOTS}",
        ivec("SWEEP_P", sweep_p),
        fvec("chain_gather_data", data),
        fvec("chain_gather_golden_lin", golden_lin),
        fvec("chain_gather_moment_data", mom),
        fvec("chain_gather_golden_mom", golden_mom),
    ]
    return "\n\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Generating data for the ChainGather scaling sweep")
    parser.add_argument("-c", "--cfg", type=pathlib.Path, required=True,
                        help="Select param config file")
    args = parser.parse_args()
    with args.cfg.open() as f:
        param = hjson.loads(f.read())
    print(emit_header_file(**param))


if __name__ == "__main__":
    main()
